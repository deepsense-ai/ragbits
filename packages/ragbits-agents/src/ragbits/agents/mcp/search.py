from ragbits.agents.mcp.server import MCPServerStreamableHttp, MCPServerStreamableHttpParams


class MCPServerWebSearch(MCPServerStreamableHttp):
    """
    Web search and page fetching through a Streamable HTTP MCP server.

    Without server parameters, use Parallel Search MCP anonymously. Search uses
    Fast mode and does not require an account or API key. Attach this server to an
    Agent's ``mcp_servers`` to enable its tools.

    Connection management, tool discovery and execution use the same MCP client
    as ``MCPServerStreamableHttp``. No conversation identifier is generated by
    the server: callers that supply ``session_id`` tool arguments should reuse
    one opaque identifier per conversation, independently of this connection.
    """

    def __init__(
        self,
        params: MCPServerStreamableHttpParams | None = None,
        cache_tools_list: bool = True,
        name: str | None = None,
        client_session_timeout_seconds: float | None = 60,
    ) -> None:
        """
        Configure web search, defaulting to Parallel when params are omitted.

        Args:
            params: Explicit server configuration, used instead of the default
                Parallel endpoint. Supports custom URLs, authorization headers
                and transport timeouts. No environment credentials are read.
                A ``ragbits-agents`` User-Agent is added unless one is supplied.
            cache_tools_list: Whether to cache discovered tools. Defaults to True;
                call ``invalidate_tools_cache()`` to refresh discovery.
            name: A readable server name. Defaults to ``web-search``.
            client_session_timeout_seconds: MCP response timeout, in seconds.
                Defaults to 60 to allow page fetching to complete.
        """
        resolved_params: MCPServerStreamableHttpParams = (
            {"url": "https://search.parallel.ai/mcp", "timeout": 30} if params is None else {**params}
        )
        headers = dict(resolved_params.get("headers", {}))
        if not any(key.lower() == "user-agent" for key in headers):
            headers["User-Agent"] = "ragbits-agents"
        resolved_params["headers"] = headers
        super().__init__(
            params=resolved_params,
            cache_tools_list=cache_tools_list,
            name=name or "web-search",
            client_session_timeout_seconds=client_session_timeout_seconds,
        )
